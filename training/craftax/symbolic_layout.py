"""Flat symbolic observation layout for full Craftax (``render_craftax_symbolic``)."""

from __future__ import annotations

from craftax.craftax.constants import OBS_DIM, BlockType, ItemType

from configs.craftax_base import CRAFTAX_OBS_SIZE

_NUM_BLOCK_TYPES = int(len(BlockType))
_NUM_ITEM_TYPES = int(len(ItemType))
_MOB_TYPES_PER_CLASS = 8
_NUM_MOB_CHANNELS = 5 * _MOB_TYPES_PER_CLASS
_NUM_LIGHT_CHANNELS = 1
_SYMBOLIC_CHANNELS_PER_CELL = (
    _NUM_BLOCK_TYPES + _NUM_ITEM_TYPES + _NUM_MOB_CHANNELS + _NUM_LIGHT_CHANNELS
)
_SYMBOLIC_MAP_FLAT = int(OBS_DIM[0] * OBS_DIM[1] * _SYMBOLIC_CHANNELS_PER_CELL)
_SYMBOLIC_TAIL = int(CRAFTAX_OBS_SIZE - _SYMBOLIC_MAP_FLAT)

assert CRAFTAX_OBS_SIZE == _SYMBOLIC_MAP_FLAT + _SYMBOLIC_TAIL, (
    CRAFTAX_OBS_SIZE,
    _SYMBOLIC_MAP_FLAT,
    _SYMBOLIC_TAIL,
)

_SYMBOLIC_INVENTORY_LEN = 17
_SYMBOLIC_POTIONS_LEN = 6
_SYMBOLIC_INTRINSICS_LEN = 9
_SYMBOLIC_DIRECTION_LEN = 4

_SYMBOLIC_INVENTORY_START = _SYMBOLIC_MAP_FLAT
_SYMBOLIC_POTIONS_START = _SYMBOLIC_INVENTORY_START + _SYMBOLIC_INVENTORY_LEN
_SYMBOLIC_INTRINSICS_START = _SYMBOLIC_POTIONS_START + _SYMBOLIC_POTIONS_LEN
_SYMBOLIC_HEALTH_IDX = _SYMBOLIC_INTRINSICS_START
_SYMBOLIC_FOOD_IDX = _SYMBOLIC_INTRINSICS_START + 1
_SYMBOLIC_DRINK_IDX = _SYMBOLIC_INTRINSICS_START + 2
_SYMBOLIC_ENERGY_IDX = _SYMBOLIC_INTRINSICS_START + 3
_SYMBOLIC_DIR_START = _SYMBOLIC_INTRINSICS_START + _SYMBOLIC_INTRINSICS_LEN

_SYMBOLIC_PLAYER_ROW = int(OBS_DIM[0] // 2)
_SYMBOLIC_PLAYER_COL = int(OBS_DIM[1] // 2)

# Mob channel slices within each map cell (after block + item one-hot).
_MOB_SLICE_START = _NUM_BLOCK_TYPES + _NUM_ITEM_TYPES
_MELEE_MOB_SLICE = slice(_MOB_SLICE_START, _MOB_SLICE_START + _MOB_TYPES_PER_CLASS)
_PASSIVE_MOB_SLICE = slice(
    _MOB_SLICE_START + _MOB_TYPES_PER_CLASS,
    _MOB_SLICE_START + 2 * _MOB_TYPES_PER_CLASS,
)
_PROJECTILE_MOB_SLICE = slice(
    _MOB_SLICE_START + 3 * _MOB_TYPES_PER_CLASS,
    _MOB_SLICE_START + 4 * _MOB_TYPES_PER_CLASS,
)
# Relative to ``map3[..., _MOB_SLICE_START:]`` (do not reuse absolute slices there).
_MELEE_MOB_REL = slice(0, _MOB_TYPES_PER_CLASS)
_PASSIVE_MOB_REL = slice(_MOB_TYPES_PER_CLASS, 2 * _MOB_TYPES_PER_CLASS)
_PROJECTILE_MOB_REL = slice(3 * _MOB_TYPES_PER_CLASS, 4 * _MOB_TYPES_PER_CLASS)
